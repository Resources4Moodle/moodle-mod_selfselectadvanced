namespace mod_selfselectadvanced\form;

defined('MOODLE_INTERNAL') || die();

require_once($CFG->libdir . '/formslib.php');

/**
 * Group proposal upload (one document; spec change 2026-07-24).
 *
 * Custom data: fileoptions (filemanager options array).
 *
 * @package    mod_selfselectadvanced
 * @copyright  2026 JSP <jsp@jsp.net.in>
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class proposal_form extends \moodleform {
    /**
     * Define the form elements.
     */
    protected function definition(): void {
        $mform = $this->_form;

        $mform->addElement(
            'filemanager',
            'proposal',
            get_string('proposal', 'mod_selfselectadvanced'),
            null,
            $this->_customdata['fileoptions']
        );
        $mform->addHelpButton('proposal', 'proposal', 'mod_selfselectadvanced');

        $this->add_action_buttons();
    }
}
