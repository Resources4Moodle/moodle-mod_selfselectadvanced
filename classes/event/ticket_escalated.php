namespace mod_selfselectadvanced\event;

/**
 * Event fired when a queue ticket changes: it was escalated to the
 * editing-teacher/manager tier (1.20.44, the handling ladder's
 * "escalate" rung).
 *
 * @package    mod_selfselectadvanced
 * @copyright  2026 JSP <jsp@jsp.net.in>
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class ticket_escalated extends \core\event\base {
    /**
     * Initialise the event data.
     */
    protected function init(): void {
        $this->data['objecttable'] = 'selfselectadvanced_ticket';
        $this->data['crud'] = 'u';
        $this->data['edulevel'] = self::LEVEL_OTHER;
    }

    /**
     * Localised event name.
     *
     * @return string
     */
    public static function get_name(): string {
        return get_string('eventticketescalated', 'mod_selfselectadvanced');
    }

    /**
     * Human-readable description.
     *
     * @return string
     */
    public function get_description(): string {
        $type = $this->other['type'] ?? '';

        return "The user with id '$this->userid' escalated the '$type' ticket with id "
            . "'$this->objectid' in the activity with course module id '$this->contextinstanceid'.";
    }

    /**
     * URL to the ticket queue.
     *
     * @return \moodle_url
     */
    public function get_url(): \moodle_url {
        return new \moodle_url('/mod/selfselectadvanced/tickets.php', [
            'id' => $this->contextinstanceid,
        ]);
    }
}
